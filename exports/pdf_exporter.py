        story = []
        score = report.get("overall_score", 0)
        status = report.get("verification_status", "Passed")

        story.append(Paragraph("Quality Control Audit: Research & Factual Accuracy", self.styles["DocTitle"]))
        story.append(Paragraph(f"Audited Lesson: <b>{title}</b> &nbsp;|&nbsp; Auditor: QC Agent 1 (Independent)", self.styles["DocSubtitle"]))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#059669"), spaceAfter=12))

        # Score Banner
        score_table = Table([[
            Paragraph(f"<b>Overall Factual Accuracy:</b> {score} / 100", self.styles["SectionHeading"]),
            Paragraph(f"<b>Verification Status:</b> {status}", self.styles["SectionHeading"])
        ]], colWidths=[252, 252])
        score_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ecfdf5")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#a7f3d0")),
            ("PADDING", (0, 0), (-1, -1), 10),
        ]))
        story.append(score_table)
        story.append(Spacer(1, 14))

        # Claims breakdown
        eval_table = Table([[
            Paragraph(f"Claims Evaluated: <b>{report.get('claims_evaluated_count', 0)}</b>", self.styles["BodyDark"]),
            Paragraph(f"Supported Claims: <b>{report.get('supported_claims_count', 0)}</b>", self.styles["BodyDark"]),
            Paragraph(f"Unsupported Claims: <b>{report.get('unsupported_claims_count', 0)}</b>", self.styles["BodyDark"]),
            Paragraph(f"Questionable: <b>{report.get('questionable_claims_count', 0)}</b>", self.styles["BodyDark"])
        ]], colWidths=[126, 126, 126, 126])
        eval_table.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("PADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(eval_table)
        story.append(Spacer(1, 14))

        story.append(Paragraph("Identified Factual Issues & Suggested Corrections:", self.styles["SectionHeading"]))
        issues = report.get("identified_issues", [])
        if issues:
            for idx, iss in enumerate(issues, 1):
                box = Table([
                    [Paragraph(f"<b>Issue #{idx}: [{iss.get('severity', 'Medium')}] {iss.get('issue_type')}</b>", self.styles["SubsectionHeading"])],
                    [Paragraph(f"<b>Audited Claim:</b> {iss.get('claim')}", self.styles["BodyDark"])],
                    [Paragraph(f"<b>Auditor Analysis:</b> {iss.get('explanation')}", self.styles["BodyDark"])],
                    [Paragraph(f"<b>Suggested Correction:</b> {iss.get('suggested_correction')}", self.styles["CalloutText"])]
                ], colWidths=[504])
                box.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fff7ed")),
                    ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#fed7aa")),
                    ("PADDING", (0, 0), (-1, -1), 7),
                ]))
                story.append(box)
                story.append(Spacer(1, 6))
        else:
            story.append(Paragraph("✅ All evaluated claims are fully supported by retrieved research sources.", self.styles["BodyDark"]))

        story.append(Spacer(1, 10))
        story.append(Paragraph("Auditor Final Summary:", self.styles["SectionHeading"]))
        story.append(Paragraph(report.get("final_summary", ""), self.styles["BodyDark"]))

        doc.build(story, canvasmaker=NumberedCanvas)
        return output_path

